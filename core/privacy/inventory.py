def lookup_record(record_id: str) -> DataClassRecord | None:
    for row in DATA_INVENTORY:
        if row.id == record_id:
            return row
    return None


def inventory_as_dicts() -> list[dict[str, Any]]:
    return [asdict(r) for r in DATA_INVENTORY]
